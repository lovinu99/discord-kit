async function send(name, payload) {
  console.log(`\n📤 ${name}...`);
  try {
    const result = await notify('main', payload);
    console.log(`   ✅ Sent: ${result.status} (attempts: ${result.attempts})`);
    return result;
  } catch (e) {
    console.error(`   ❌ Failed: ${e.message}`);
    if (e.status) console.error(`   Status: ${e.status}`);
    throw e;
  }
}

